def horizon_end(t):
    """Конец окна метки для даты среза t."""
    t = pd.Timestamp(t)
    end = t + pd.DateOffset(months=HORIZON_MONTHS)
    return end + pd.offsets.MonthEnd(0) if t.is_month_end else end   # 30.06 → 31.12, а не 30.12
